import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { ROOT } from '../lib/config.mjs';

const result = await build({
  absWorkingDir: ROOT,
  entryPoints: ['editor/vim-editor.js'],
  outfile: 'public/vendor/vim-editor.js',
  bundle: true, format: 'esm', target: ['es2022'], minify: true, metafile: true,
  legalComments: 'eof',
  banner: { js: '// Generated by npm run build:editor. See vim-editor.LICENSE.txt for bundled licenses.' },
});
const packages = new Map();
for (const input of Object.keys(result.metafile.inputs)) {
  if (!input.startsWith('node_modules/')) continue;
  let directory = path.dirname(path.join(ROOT, input));
  while (directory.startsWith(path.join(ROOT, 'node_modules'))) {
    try {
      const pkg = JSON.parse(await readFile(path.join(directory, 'package.json'), 'utf8'));
      if (pkg.name && !packages.has(pkg.name)) {
        let license;
        for (const name of ['LICENSE', 'LICENSE.txt', 'LICENSE.md']) {
          try { license = await readFile(path.join(directory, name), 'utf8'); break; } catch {}
        }
        if (!license) throw new Error(`Missing license for bundled package ${pkg.name}`);
        packages.set(pkg.name, `${pkg.name} ${pkg.version}\n\n${license.trim()}`);
      }
      break;
    } catch (error) { if (error.code !== 'ENOENT') throw error; }
    directory = path.dirname(directory);
  }
}
await writeFile(path.join(ROOT, 'public/vendor/vim-editor.LICENSE.txt'), [...packages].sort(([a], [b]) => a.localeCompare(b)).map(([, text]) => text).join('\n\n--------------------\n\n') + '\n');
console.log(`Built offline Vim editor; retained licenses for ${packages.size} bundled packages.`);
