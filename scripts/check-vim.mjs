// Uses the same optional Playwright installation as check-ui.mjs.
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { createApp } from '../server.mjs';

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright-core');
const data = await mkdtemp(path.join(os.tmpdir(), 'zig-tigerbeetle-course-vim-'));
const server = createApp({ dataDirectory: data });
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const base = `http://127.0.0.1:${server.address().port}`;
let browser;
try {
  browser = await chromium.launch({ executablePath: process.env.CHROMIUM_BIN || '/usr/bin/chromium', headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage'] });
  const page = await browser.newPage();
  const errors = [], external = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.route('**/*', async route => {
    if (route.request().url().startsWith(base)) await route.continue();
    else { external.push(route.request().url()); await route.abort(); }
  });
  await page.goto(`${base}/#lesson/values`);
  const regular = page.getByRole('textbox', { name: 'Zig source code editor' });
  await regular.fill('alpha beta\ngamma delta\nthird line\n');
  await page.getByRole('button', { name: 'Vim: off', exact: true }).click();
  const vim = page.locator('.cm-content:visible');
  const text = () => page.locator('#code-input').inputValue();
  const mode = async expected => page.waitForFunction(value => document.querySelector('#vim-mode').textContent === value, expected);
  const keys = async value => { for (const key of value) await page.keyboard.press(key); };
  await vim.waitFor();
  await mode('NORMAL');
  assert.equal(await vim.evaluate(el => getComputedStyle(el).fontSize), await page.locator('#code-input').evaluate(el => getComputedStyle(el).fontSize));
  assert.equal(await page.locator('.cm-vim-panel:visible').count(), 0);
  await vim.click();
  await keys('gg0');
  await page.keyboard.press('i');
  await mode('INSERT');
  await page.keyboard.type('new ');
  await page.keyboard.press('Escape');
  await mode('NORMAL');
  assert.equal(await text(), 'new alpha beta\ngamma delta\nthird line\n');
  await page.keyboard.press('u');
  assert.equal(await text(), 'alpha beta\ngamma delta\nthird line\n');
  await page.keyboard.press('Control+r');
  assert.equal(await text(), 'new alpha beta\ngamma delta\nthird line\n');
  await keys('gg0w');
  assert.equal(await page.locator('#cursor-position').textContent(), 'Ln 1, Col 5');
  await keys('b');
  assert.equal(await page.locator('#cursor-position').textContent(), 'Ln 1, Col 1');
  await keys('vll');
  await mode('VISUAL');
  await page.keyboard.press('y');
  await mode('NORMAL');
  await page.keyboard.press('p');
  assert.equal(await text(), 'nnewew alpha beta\ngamma delta\nthird line\n');
  await page.keyboard.press('u');
  await keys('ggVj');
  await mode('VISUAL LINE');
  await page.keyboard.press('Escape');
  await keys('gg0');
  await page.keyboard.press('Control+v');
  await page.keyboard.press('j');
  await mode('VISUAL BLOCK');
  await page.keyboard.press('Escape');
  await keys('gg0dw');
  assert.equal(await text(), 'alpha beta\ngamma delta\nthird line\n');
  await page.keyboard.press('.');
  assert.equal(await text(), 'beta\ngamma delta\nthird line\n');
  await page.keyboard.press('u');
  await page.keyboard.press('u');
  await keys('gg2j');
  assert.equal(await page.locator('#cursor-position').textContent(), 'Ln 3, Col 1');
  await keys('ggyy');
  await page.keyboard.press('p');
  assert.equal(await text(), 'new alpha beta\nnew alpha beta\ngamma delta\nthird line\n');
  await page.keyboard.press('u');
  await keys('gg0ciw');
  await mode('INSERT');
  await page.keyboard.type('changed');
  await page.keyboard.press('Escape');
  const draft = 'changed alpha beta\ngamma delta\nthird line\n';
  assert.equal(await text(), draft);
  await page.keyboard.type('/gamma');
  assert.ok((await page.locator('.cm-vim-panel:visible').boundingBox()).height <= 40);
  await page.keyboard.press('Enter');
  assert.ok((await page.locator('#cursor-position').textContent()).startsWith('Ln 2,'));
  await page.keyboard.type(':w');
  await page.keyboard.press('Enter');
  await page.waitForFunction(() => document.querySelector('#save-state').textContent === 'Saved locally');
  assert.equal((await (await page.request.get(`${base}/api/progress`)).json()).drafts.values, draft);
  await page.getByRole('tab', { name: 'Tests', exact: true }).click();
  await page.getByRole('textbox', { name: 'Read-only course tests' }).waitFor();
  const checks = await text();
  await vim.click();
  await keys('ggdd');
  await page.keyboard.press('u');
  await page.keyboard.type(':%d');
  await page.keyboard.press('Enter');
  await page.keyboard.press('i');
  await page.keyboard.type('cannot edit');
  await page.keyboard.press('Escape');
  assert.equal(await text(), checks);
  await page.getByRole('tab', { name: 'main.zig', exact: true }).click();
  assert.equal(await text(), draft);
  await vim.click();
  await page.keyboard.press('u');
  assert.notEqual(await text(), draft, 'source undo history survives visiting Tests');
  await page.keyboard.press('Control+r');
  assert.equal(await text(), draft);
  await page.reload();
  await page.getByRole('button', { name: 'Vim: on', exact: true }).waitFor();
  await vim.waitFor();
  assert.equal(await text(), draft);
  await page.getByRole('button', { name: 'Vim: on', exact: true }).click();
  await regular.waitFor();
  assert.equal(await regular.inputValue(), draft);
  await page.getByRole('button', { name: 'Vim: off', exact: true }).click();
  await vim.waitFor();
  await page.goto(`${base}/#playground`);
  await vim.waitFor();
  await vim.click();
  await page.keyboard.press('Control+Enter');
  await page.locator('#terminal-output').filter({ hasText: 'Welcome to your Zig workshop!' }).waitFor();
  await page.getByRole('button', { name: 'Format', exact: true }).click();
  await page.locator('#terminal-status').filter({ hasText: 'Passed' }).waitFor();
  await page.goto(`${base}/#lesson/tb-create-accounts`);
  await page.getByRole('textbox', { name: 'TigerBeetle REPL editor' }).waitFor();
  await page.goto(`${base}/#lesson/tb-source-map`);
  await page.getByRole('textbox', { name: 'Source evidence editor' }).waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: '/tmp/zig-tigerbeetle-course-vim-mobile.png', fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.getByRole('button', { name: 'Vim keybindings help' }).click();
  await page.getByRole('heading', { name: 'Vim keybindings', exact: true }).waitFor();
  assert.deepEqual(errors, []);
  assert.deepEqual(external, []);
  console.log('Vim passed: modes, motions, counts, operators, text objects, yank/paste, undo/redo/repeat, search, :w, read-only tests, history across tabs, persistence, toggle, compiler shortcut, all editor types, mobile, and offline assets.');
} finally {
  await browser?.close();
  await new Promise(resolve => server.close(resolve));
  await rm(data, { recursive: true, force: true });
}
